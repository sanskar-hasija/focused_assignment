"""Write evals/review.md, the review sheet for every example: make review."""

from pathlib import Path

from app.seed_data import BUILDINGS, FLATS, TENANTS
from evals.examples import EXAMPLES
from evals.schema import EvalExample

REVIEW_PATH = Path(__file__).resolve().parent / "review.md"

FLAT_BUILDING = {flat.id: flat.building_id for flat in FLATS}
BUILDING_NAME = {building.id: building.name for building in BUILDINGS}
TENANT_FLAT = {tenant.id: tenant.flat_id for tenant in TENANTS}

COLUMNS = [
    "id", "tenant", "season", "message", "expected issues",
    "gold", "forbidden", "include", "exclude", "notes",
]  # fmt: skip


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _list(items: list[str]) -> str:
    return ", ".join(f"`{item}`" for item in items) or "-"


def _season(example: EvalExample) -> str:
    month = example.inputs.now.month
    return "heating season" if month >= 10 or month <= 4 else "summer"


def _issues(example: EvalExample) -> str:
    issues = example.reference.issues
    text = "<br>".join(f"{i.category}/{i.priority}/{i.ticket}" for i in issues) or "[]"
    if example.inputs.fail_create_ticket:
        text += "<br>**ticketing down**"
    return text


def _row(example: EvalExample) -> list[str]:
    flat_id = TENANT_FLAT[example.inputs.tenant_id]
    building = BUILDING_NAME[FLAT_BUILDING[flat_id]]
    ref = example.reference
    return [
        f"**{example.id}**",
        f"{example.inputs.tenant_id} · {flat_id} {building}",
        _season(example),
        _cell(example.inputs.message),
        _issues(example),
        _list(ref.gold_clauses),
        _list(ref.forbidden_clauses),
        _list(ref.reply_must_include),
        _list(ref.reply_must_not_include),
        _cell(example.metadata.notes),
    ]


def render(examples: list[EvalExample]) -> str:
    split_order = {"dev": 0, "heldout": 1}
    ordered = sorted(examples, key=lambda e: (split_order[e.metadata.split], e.id))
    lines = [
        "# Eval dataset review",
        "",
        "Generated by `make review` from evals/examples.py; edit the examples, not this file.",
        "Labels follow [docs/labelling.md](../docs/labelling.md). Issues are"
        " category/priority/ticket. D = dev, H = held out.",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "---|" * len(COLUMNS),
    ]
    lines += ["| " + " | ".join(_row(example)) + " |" for example in ordered]
    return "\n".join(lines) + "\n"


def main() -> None:
    REVIEW_PATH.write_text(render(EXAMPLES))
    print(f"Wrote evals/review.md ({len(EXAMPLES)} examples)")


if __name__ == "__main__":
    main()
