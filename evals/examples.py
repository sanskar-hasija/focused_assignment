MANUAL_RUNS = {"D01", "D02", "D03", "D04"}


def _issue(spec: str) -> Issue:
    category, priority, ticket = spec.split("/")
    return Issue(category=category, priority=priority, ticket=ticket)


def ex(
    id: str,
    tenant_id: str,
    now: datetime,
    message: str,
    issues: list[str],
    *,
    slices: list[Slice],
    notes: str,
    gold: tuple[str, ...] = (),
    forbid: tuple[str, ...] = (),
    include: tuple[str, ...] = (),
    exclude: tuple[str, ...] = (),
    fail: bool = False,
) -> EvalExample:
    heldout = id.startswith("H")
    return EvalExample(
        id=id,
        inputs={"message": message, "tenant_id": tenant_id, "now": now, "fail_create_ticket": fail},
        reference={
            "issues": [_issue(spec) for spec in issues],
            "gold_clauses": gold,
            "forbidden_clauses": forbid,
            "reply_must_include": include,
            "reply_must_not_include": exclude,
        },
        metadata={
            "slices": slices,
            "split": "heldout" if heldout else "dev",
            "origin": "variant" if heldout else "manual_run" if id in MANUAL_RUNS else "catalogue",
            "notes": notes,
        },
    )


